#!/usr/bin/env python3
"""Генерация «РАЗДЕЛ 5. Контрольный пример» для веб-приложения (ветка main)."""

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "Раздел_5_Контрольный_пример.docx"


def figure(doc, num, caption):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(f"[ Вставьте рисунок {num} ]")
    r.italic = True
    r.font.size = Pt(11)
    c = doc.add_paragraph(f"Рисунок {num} – {caption}")
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    c.runs[0].italic = True
    doc.add_paragraph()


def build():
    doc = Document()
    s = doc.sections[0]
    s.top_margin = Cm(2)
    s.bottom_margin = Cm(2)
    s.left_margin = Cm(3)
    s.right_margin = Cm(1.5)

    h = doc.add_heading("РАЗДЕЛ 5 КОНТРОЛЬНЫЙ ПРИМЕР", 0)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_paragraph(
        "Контрольный пример выполняется для веб-приложения «3D-визуализация учебного "
        "оборудования» Алтайского промышленно-экономического колледжа. Сервер запускается "
        "командой docker compose up -d --build (или npm start). В браузере открывается адрес "
        "http://<IP-сервера>:8080/."
    )

    doc.add_paragraph(
        "После старта программы отображается главная страница, изображённая на рисунке 16."
    )
    figure(doc, 16, "Главная страница веб-приложения")

    doc.add_paragraph("На главной странице можно увидеть:")
    items = [
        "Шапку сайта с названием «Учебное оборудование Алтайского Промышленно-Экономического "
        "колледжа» и кнопкой меню (три горизонтальные полоски) в правом верхнем углу.",
        "Блок приветствия с кнопками «Выбрать специальность» и «Открыть 3D просмотр».",
        "Раздел «Выберите специальность». Карточки ОИБ, ПД и ЗЕМ; в текущей версии "
        "активна только специальность ПД, остальные отмечены как «В разработке».",
        "Раздел «Оборудование и 3D модель»: слева — прокручиваемый список объектов, "
        "справа — просмотрщик model-viewer, описание, особенности, кнопки «Автопрокрутка» "
        "и «Открыть GLB-источник».",
        "Подвал: подпись проекта, кнопка GitHub (открывает репозиторий в новой вкладке), "
        "ссылки «Файлы cookie» и «Политика конфиденциальности» (модальные окна).",
    ]
    for t in items:
        doc.add_paragraph(t, style="List Number")

    doc.add_heading("Меню «бургер»", level=2)
    doc.add_paragraph(
        "Нажмите левой кнопкой мыши на кнопку с тремя полосками (рисунок 17). "
        "Список пунктов появляется только после нажатия; иконка выровнена по центру кнопки. "
        "Повторное нажатие или клик вне меню закрывает список."
    )
    figure(doc, 17, "Кнопка меню (бургер)")

    doc.add_paragraph("В выпадающем меню (рисунок 18) доступны пункты:")
    for t in [
        "«Загрузить модель» — запрос пароля и переход в админ-панель;",
        "«База знаний (FAQ)» — справочные статьи из базы SQLite;",
        "«О нас» — описание проекта.",
    ]:
        doc.add_paragraph(t, style="List Number")
    figure(doc, 18, "Открытое выпадающее меню")

    doc.add_heading("Просмотр каталога и 3D-модели", level=2)
    doc.add_paragraph(
        "В разделе специальностей нажмите карточку «ПД» (рисунок 19). Карточки ОИБ и ЗЕМ "
        "недоступны для выбора."
    )
    figure(doc, 19, "Выбор специальности ПД")

    doc.add_paragraph(
        "В левом списке выберите объект оборудования (рисунок 20). Справа загрузится "
        "GLB-модель, обновятся название, тип, описание и список особенностей. "
        "Модель можно вращать мышью или касанием; кнопки «−», «100%», «+» меняют масштаб."
    )
    figure(doc, 20, "Список оборудования и 3D-просмотрщик")

    doc.add_paragraph(
        "Кнопка «Автопрокрутка: вкл/выкл» включает или отключает автоматическое вращение "
        "модели (рисунок 21)."
    )
    figure(doc, 21, "Управление просмотром 3D-модели")

    doc.add_heading("Подвал сайта", level=2)
    doc.add_paragraph(
        "Внизу главной страницы (рисунок 22) нет текста о «статическом сайте». "
        "Нажмите кнопку с иконкой GitHub — откроется https://github.com/may539/Diplom."
    )
    figure(doc, 22, "Подвал с кнопкой GitHub")

    doc.add_paragraph(
        "Нажмите «Файлы cookie» или «Политика конфиденциальности» — откроются модальные "
        "окна с текстом (рисунки 23 и 24). Закрытие — кнопка «×» или клик по затемнённой области."
    )
    figure(doc, 23, "Модальное окно «Файлы cookie»")
    figure(doc, 24, "Модальное окно «Политика конфиденциальности»")

    doc.add_heading("База знаний и раздел «О нас»", level=2)
    doc.add_paragraph(
        "В меню «бургер» выберите «База знаний (FAQ)». Откроется окно со статьями, "
        "загруженными с сервера (GET /api/help-articles). Раскройте заголовок статьи, "
        "чтобы прочитать текст (рисунок 25)."
    )
    figure(doc, 25, "Модальное окно FAQ")

    doc.add_paragraph("Пункт «О нас» открывает краткое описание назначения системы (рисунок 26).")
    figure(doc, 26, "Модальное окно «О нас»")

    doc.add_heading("Добавление модели и QR-код (админ-панель)", level=2)
    doc.add_paragraph(
        "В меню выберите «Загрузить модель». В модальном окне (рисунок 27) введите "
        "мастер-пароль (ADMIN_PASSWORD в .env) и нажмите «Открыть форму». "
        "При верном пароле выполняется переход на страницу /admin.html."
    )
    figure(doc, 27, "Ввод пароля администратора на главной странице")

    doc.add_paragraph(
        "На странице админ-панели заполните форму (рисунок 28): специальность, название, "
        "тип, описания, особенности; укажите URL GLB или выберите файл .glb. "
        "Нажмите «Добавить модель и сгенерировать QR»."
    )
    figure(doc, 28, "Форма добавления 3D-модели в админ-панели")

    doc.add_paragraph(
        "После сохранения появится модальное окно с QR-кодом (рисунок 29). "
        "Ссылка ведёт на /view.html?id=<идентификатор> — полноэкранный просмотр на телефоне. "
        "Нажмите «Печать QR» для печати кода на стенд."
    )
    figure(doc, 29, "QR-код после добавления модели")

    doc.add_paragraph(
        "В блоке «QR-коды и управление объектами» (рисунок 30) отображаются все модели. "
        "Для каждой доступны кнопки: «Печать QR», «Изменить», «Удалить»."
    )
    figure(doc, 30, "Каталог объектов в админ-панели")

    doc.add_heading("Просмотр по QR на смартфоне", level=2)
    doc.add_paragraph(
        "Отсканируйте QR-код камерой телефона. Откроется страница view.html (рисунок 31): "
        "3D-модель на весь экран, вверху — тип и название объекта. "
        "Управление — жестами (вращение, масштаб)."
    )
    figure(doc, 31, "Полноэкранный просмотр на мобильном устройстве (view.html)")

    doc.add_paragraph(
        "Контрольный пример подтверждает работу: каталога ПД, динамической загрузки моделей "
        "из SQLite, меню «бургер», подвала с GitHub и юридическими модальными окнами, "
        "админ-панели с QR и полноэкранного режима для мобильных устройств."
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUTPUT)
    return OUTPUT


if __name__ == "__main__":
    print(f"Saved: {build()}")
