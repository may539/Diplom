def heading(doc, text, level=1):
    h = doc.add_heading(text, level=level)
    if level == 0:
        h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return h


def body(doc, text):
    doc.add_paragraph(text)


def numbered(doc, items):
    for item in items:
        doc.add_paragraph(item, style="List Number")


